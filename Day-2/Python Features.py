# Programming Paradigms

# Procedural Programming

# Procedural programming is a programming style where the program is
# written as a sequence of functions. The focus is on solving problems
# step by step.

# Advantages
# Easy to learn
# Good for small programs
# Less memory usage

# Disadvantages
# Difficult to manage large projects
# Less code reusability
# Lower data security


# Object-Oriented Programming (OOP)

# OOP is a programming style where programs are built using classes
# and objects. It combines data and functions into a single unit.

# Advantages
# Code Reusability
# Better Security
# Easy Maintenance
# Real-world Modeling
# Suitable for Large Projects


# OOP Concepts

# Class
# A class is a blueprint for creating objects.

# Object
# An object is an instance of a class.

# Encapsulation
# Wrapping data and methods into a single unit.
# It provides data security.

# Abstraction
# Hiding implementation details and showing only essential information.

# Inheritance
# One class acquires properties and methods of another class.
# It improves code reusability.

# Polymorphism
# One method behaves differently for different objects.


# Difference Between Procedural Programming and OOP

# Procedural Programming
# Function-based
# Focus on procedures
# Less secure
# Suitable for small projects
# Data and functions are separate

# Object-Oriented Programming
# Class-based
# Focus on objects
# More secure
# Suitable for large projects
# Data and methods are together


